'use strict';
const assert=require('node:assert/strict');
const {RouteEngine,defaults,wheelMotion}=require('../vehicle-route.js');
const gas=require('../route-gas.js'),sonar=require('../sonar-projection.js');
const e=new RouteEngine({...defaults(),confirmed:true});
for(const ms of [0,80,160,240,320])e.rememberPose(ms,false,1000);
assert.equal(e.stationaryAt(239),false);assert.equal(e.stationaryAt(280),true);
e.heading=.1;e.rememberPose(400,false,1000);assert.equal(e.stationaryAt(375),false);
e.x=.04;e.distance=.04;e.rememberPose(480,false,1000);assert.equal(e.stationaryAt(480),false);
for(const ms of [560,640,720,800])e.rememberPose(ms,false,1000);
assert.equal(e.stationaryAt(800),true);e.rememberPose(880,true,1000);assert.equal(e.stationaryAt(880),false);
assert(wheelMotion({vehicle:{online:true,state:4}}));
assert(wheelMotion({wheelSpeed:{online:true,valid:true,ageMs:30,measuredRpm10:[20,-20,20,-20]}}));
assert(!wheelMotion({wheelSpeed:{online:true,valid:true,ageMs:600,measuredRpm10:[20,-20,20,-20]}}));
e.online=true;e.lastReceived=1000;e.rememberPose(960,false,1000);
const sample={level:'normal',key:'',detail:''};
gas.observe(e,sample,1000);e.distance+=.04;gas.observe(e,sample,1000);assert.equal(e.gasMarks.length,1);
e.distance+=.021;gas.observe(e,sample,1000);gas.observe(e,{...sample,level:'alarm'},1000);assert.equal(e.gasMarks.length,3);
const run=[0,.1,.2,.3,.3,.3].map(x=>({x,y:.3,z:.6,yaw:0,pitch:0,head:0,commands:[0,0],station:String(x),distance:60}));
assert.equal(sonar.resolve(run,{legacyTravel:true}).travel,3);
assert.equal(sonar.resolve(run.map(p=>({...p,stationary:true})),{legacyTravel:true}).travel,0);
assert.equal(sonar.resolve(run,{raw:true,legacyTravel:true}).excluded.size,0);
const low={...run[0],pitch:-30,y:-1};
assert.equal(sonar.resolve([low]).belowFloor,1);
assert.equal(sonar.resolve([low,{...low,yaw:2}]).belowFloor,0);
console.log('PASS stopped, translating, pivoting and gap samples; gas spacing, legacy fixed beam and below-floor support');
